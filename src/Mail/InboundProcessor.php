<?php
declare(strict_types=1);

namespace Bakkbone\HelpCentre\Mail;

use Bakkbone\HelpCentre\Core\App;
use Bakkbone\HelpCentre\Core\Html;
use Bakkbone\HelpCentre\Core\Log;
use Bakkbone\HelpCentre\Core\Settings;
use Bakkbone\HelpCentre\Services\Attachments;
use Bakkbone\HelpCentre\Services\EmailAccounts;
use Bakkbone\HelpCentre\Services\Staff;
use Bakkbone\HelpCentre\Services\Tickets;
use Bakkbone\HelpCentre\Services\Users;

final class InboundProcessor
{
    /** @return array{status:'created'|'appended'|'ignored'|'rejected',ticket_id?:int,reason?:string} */
    public static function process(string $raw, ?array $account = null, string $via = 'pipe'): array
    {
        $mail = MimeParser::parse($raw);
        $db = App::db();

        if ($db->val('SELECT ticket_id FROM thread_entries WHERE message_id = ? LIMIT 1', [$mail->messageId])) {
            return ['status' => 'ignored', 'reason' => 'Duplicate message (already processed)'];
        }
        if ($mail->isBounce()) {
            Log::warning('Bounce / delivery report received', 'From: ' . $mail->fromEmail . "\nSubject: " . $mail->subject . "\nVia: $via");
            return ['status' => 'ignored', 'reason' => 'Delivery status notification'];
        }
        $sender = $mail->senderEmail();
        if ($sender === '') {
            return ['status' => 'ignored', 'reason' => 'No sender address'];
        }
        $own = EmailAccounts::addresses();
        if (in_array($sender, $own, true)) {
            return ['status' => 'ignored', 'reason' => 'Message sent from a help desk mailbox (loop prevented)'];
        }

        if (!$account) {
            foreach (array_merge($mail->to, $mail->cc) as $r) {
                if ($a = EmailAccounts::byAddress($r['email'])) {
                    $account = $a;
                    break;
                }
            }
        }

        $body = self::extractBody($mail);
        $attachments = self::filterAttachments($mail);
        $others = array_values(array_filter(array_merge($mail->to, $mail->cc), fn($r) => !in_array($r['email'], $own, true) && $r['email'] !== $sender));

        [$ticket, $strong, $signed] = self::findTicket($mail, $sender);

        if ($ticket) {
            while ($ticket && $ticket['merged_into']) {
                $ticket = Tickets::find((int)$ticket['merged_into']);
            }
        }

        if ($ticket) {
            $staff = Staff::byEmail($sender);
            if ($staff && Settings::bool('staff_email_reply')) {
                // A forged From can't produce this: only mail the help desk sent for this ticket carries the signed Message-ID.
                if (!$signed) {
                    Log::warning('Agent email reply ignored (no help desk reference)', "From: $sender\nSubject: {$mail->subject}\nVia: $via");
                    return ['status' => 'rejected', 'reason' => 'Agent replies must answer a help desk email for this ticket'];
                }
                $owner = Users::find((int)$ticket['user_id']);
                $userAlreadyGotIt = $owner && in_array(strtolower($owner['email']), array_column($others, 'email'), true);
                if (Staff::canAccessTicket($staff, $ticket)) {
                    Tickets::postResponse($ticket, $staff, $body, $attachments, [
                        'source' => 'email', 'message_id' => $mail->messageId, 'notify' => !$userAlreadyGotIt, 'signature' => 'none',
                    ]);
                } else {
                    Tickets::postNote($ticket, $staff, $body, $attachments, ['source' => 'email', 'message_id' => $mail->messageId]);
                }
                return ['status' => 'appended', 'ticket_id' => (int)$ticket['id']];
            }

            $user = Users::byEmail($sender);
            $participant = $user && Tickets::isParticipant($ticket, (int)$user['id']);
            if (!$participant && $strong && !Users::isBanned($sender)) {
                $user ??= Users::findOrCreate($sender, $mail->senderName());
                Tickets::addCollaborator((int)$ticket['id'], (int)$user['id']);
                $participant = true;
            }
            if ($participant && $user) {
                if ($user['status'] === 'locked') {
                    return ['status' => 'rejected', 'reason' => 'User is locked'];
                }
                if (Settings::bool('add_cc_collaborators')) {
                    foreach ($others as $o) {
                        if (!Staff::byEmail($o['email']) && !Users::isBanned($o['email'])) {
                            $cu = Users::findOrCreate($o['email'], $o['name']);
                            Tickets::addCollaborator((int)$ticket['id'], (int)$cu['id']);
                        }
                    }
                }
                Tickets::postMessage($ticket, $user, $body, $attachments, [
                    'source' => 'email', 'message_id' => $mail->messageId, 'cc' => $others,
                    'auto_generated' => $mail->isAutoGenerated(),
                ]);
                return ['status' => 'appended', 'ticket_id' => (int)$ticket['id']];
            }
            // Not a participant and only a weak (subject) match: fall through to a new ticket.
        }

        if (!Settings::bool('accept_unknown_senders') && !Users::byEmail($sender)) {
            Log::info('Email rejected (unknown sender)', "From: $sender\nSubject: {$mail->subject}");
            return ['status' => 'rejected', 'reason' => 'Unknown sender and new users are not accepted by email'];
        }
        $result = Tickets::create([
            'email' => $sender,
            'name' => $mail->senderName(),
            'subject' => $mail->subject,
            'message' => $body,
            'source' => 'email',
            'attachments' => $attachments,
            'message_id' => $mail->messageId,
            'email_account_id' => $account['id'] ?? null,
            'to_email' => $account['email'] ?? ($mail->to[0]['email'] ?? ''),
            'cc' => $others,
            'auto_generated' => $mail->isAutoGenerated(),
        ]);
        if (!$result['ok']) {
            return ['status' => 'rejected', 'reason' => $result['error'] ?? 'Rejected'];
        }
        return ['status' => 'created', 'ticket_id' => (int)$result['ticket']['id']];
    }

    /** @return array{0:?array,1:bool,2:bool} ticket, strong match, matched a signed help desk Message-ID */
    private static function findTicket(ParsedEmail $mail, string $sender): array
    {
        $db = App::db();
        foreach ($mail->referencedIds() as $mid) {
            $tid = Mailer::ticketIdFromMessageId($mid);
            $signed = $tid !== null;
            if (!$tid) {
                $tid = (int)$db->val('SELECT ticket_id FROM thread_entries WHERE message_id = ? ORDER BY id DESC LIMIT 1', [$mid]) ?: null;
            }
            if ($tid && ($t = Tickets::find($tid))) {
                return [$t, true, $signed];
            }
        }
        if (preg_match('/\[#([A-Za-z0-9\-]{3,32})\]/', $mail->subject, $m)) {
            $t = Tickets::byNumber($m[1]);
            if ($t) {
                $user = Users::byEmail($sender);
                if (Staff::byEmail($sender) || ($user && Tickets::isParticipant($t, (int)$user['id']))) {
                    return [$t, false, false];
                }
            }
        }
        return [null, false, false];
    }

    public static function extractBody(ParsedEmail $mail): string
    {
        // The English line too, for replies to emails sent before the help desk's language was changed.
        $seps = array_values(array_unique(array_filter([trim((string)Settings::get('reply_separator')), Settings::DEFAULTS['reply_separator']])));
        if (trim($mail->htmlBody) !== '') {
            $html = $mail->htmlBody;
            if (preg_match('~<body[^>]*>(.*)</body>~is', $html, $m)) {
                $html = $m[1];
            }
            $html = preg_replace('~<(style|script|head|title)[^>]*>.*?</\1>~is', '', $html) ?? $html;
            foreach ($seps as $sep) {
                $pos = self::findSeparator($html, $sep);
                if ($pos !== null) {
                    $html = substr($html, 0, $pos);
                    $html = self::trimQuoteHeader($html, true);
                    break;
                }
            }
            $html = trim($html);
            if (trim(strip_tags($html, '<img>')) !== '') {
                return $html;
            }
        }
        $text = $mail->textBody;
        foreach ($seps as $sep) {
            $pos = mb_stripos($text, $sep);
            if ($pos !== false) {
                $text = self::trimQuoteHeader(mb_substr($text, 0, $pos), false);
                break;
            }
        }
        $text = trim($text);
        return Html::fromText($text !== '' ? $text : __('(no message body)'));
    }

    private static function findSeparator(string $html, string $sep): ?int
    {
        foreach ([$sep, htmlspecialchars($sep, ENT_QUOTES), htmlspecialchars($sep, ENT_NOQUOTES)] as $needle) {
            $p = stripos($html, $needle);
            if ($p !== false) {
                $lt = strrpos(substr($html, 0, $p), '<');
                return $lt !== false && $p - $lt < 200 ? $lt : $p;
            }
        }
        // Separator may have been split by tags (e.g. Outlook); compare on text
        $plainSep = preg_replace('/\s+/', ' ', $sep);
        $stripped = preg_replace('/\s+/', ' ', html_entity_decode(strip_tags($html)));
        if ($plainSep !== null && $stripped !== null && stripos($stripped, $plainSep) !== false) {
            foreach (['gmail_quote', 'divRplyFwdMsg', 'appendonsend', 'yahoo_quoted', 'moz-cite-prefix', '<blockquote'] as $marker) {
                $p = stripos($html, $marker);
                if ($p !== false) {
                    $lt = strrpos(substr($html, 0, $p), '<');
                    return $lt !== false ? $lt : $p;
                }
            }
        }
        return null;
    }

    private static function trimQuoteHeader(string $s, bool $html): string
    {
        if ($html) {
            foreach (['gmail_quote', 'divRplyFwdMsg', 'appendonsend', 'yahoo_quoted', 'moz-cite-prefix'] as $marker) {
                $p = stripos($s, $marker);
                if ($p !== false) {
                    $lt = strrpos(substr($s, 0, $p), '<');
                    $s = substr($s, 0, $lt !== false ? $lt : $p);
                }
            }
            $s = preg_replace('~(<(div|p)[^>]*>)?\s*On\s[^<]{5,250}wrote:\s*(</(div|p)>)?\s*(<br\s*/?>\s*)*$~is', '', $s) ?? $s;
            $s = preg_replace('~<hr[^>]*>\s*(<div[^>]*>)?\s*<(b|strong)>\s*From:.*$~is', '', $s) ?? $s;
            return $s;
        }
        $s = preg_replace('/(\n[ \t]*>?[ \t]*)+$/', '', "\n" . $s) ?? $s;
        $s = preg_replace('/\n[^\n]*\bOn\b[^\n]{5,250}\bwrote:\s*$/is', '', $s) ?? $s;
        $s = preg_replace('/\n-{2,}\s*Original Message\s*-{2,}.*$/is', '', $s) ?? $s;
        $s = preg_replace('/\n_{5,}\s*\nFrom:.*$/is', '', $s) ?? $s;
        return $s;
    }

    /** @return list<array<string,mixed>> */
    private static function filterAttachments(ParsedEmail $mail): array
    {
        if (!Settings::bool('attachments_enabled')) {
            return [];
        }
        $out = [];
        $max = Attachments::maxBytes();
        foreach ($mail->attachments as $a) {
            $isInlineImage = $a['content_id'] && str_starts_with($a['mime'], 'image/');
            if (strlen($a['content']) > $max) {
                Log::warning('Email attachment skipped (too large)', $a['filename'] . ' (' . human_size(strlen($a['content'])) . ") from {$mail->fromEmail}");
                continue;
            }
            if (!$isInlineImage && !Attachments::extensionAllowed($a['filename'])) {
                Log::info('Email attachment skipped (file type not allowed)', $a['filename'] . " from {$mail->fromEmail}");
                continue;
            }
            $out[] = $a;
        }
        return $out;
    }
}

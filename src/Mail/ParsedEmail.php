<?php
declare(strict_types=1);

namespace Bakkbone\HelpCentre\Mail;

final class ParsedEmail
{
    /** @var array<string,list<string>> */
    public array $headers = [];
    public string $subject = '';
    public string $fromEmail = '';
    public string $fromName = '';
    /** @var list<array{email:string,name:string}> */
    public array $to = [];
    /** @var list<array{email:string,name:string}> */
    public array $cc = [];
    /** @var list<array{email:string,name:string}> */
    public array $replyTo = [];
    public string $messageId = '';
    public string $inReplyTo = '';
    /** @var list<string> */
    public array $references = [];
    public ?string $date = null;
    public string $textBody = '';
    public string $htmlBody = '';
    /** @var list<array{filename:string,mime:string,content:string,content_id:?string,inline:bool}> */
    public array $attachments = [];
    public bool $isReport = false;
    public string $raw = '';

    public function header(string $name): ?string
    {
        $v = $this->headers[strtolower($name)][0] ?? null;
        return $v === null ? null : MimeParser::decodeHeader($v);
    }

    // From, never Reply-To: SPF/DKIM/DMARC don't cover Reply-To, so anyone could claim an agent's address there.
    public function senderEmail(): string
    {
        return strtolower($this->fromEmail);
    }

    public function senderName(): string
    {
        return trim($this->fromName) !== '' ? trim($this->fromName) : $this->senderEmail();
    }

    /** Never auto-respond to these. */
    public function isAutoGenerated(): bool
    {
        $as = strtolower((string)$this->header('Auto-Submitted'));
        if ($as !== '' && $as !== 'no') {
            return true;
        }
        $prec = strtolower((string)$this->header('Precedence'));
        if (in_array($prec, ['bulk', 'junk', 'list', 'auto_reply'], true)) {
            return true;
        }
        foreach (['X-Autoreply', 'X-Autorespond', 'X-Auto-Response-Suppress', 'List-Id', 'List-Unsubscribe', 'X-Loop'] as $h) {
            $v = strtolower((string)$this->header($h));
            if ($v !== '' && !($h === 'X-Auto-Response-Suppress' && $v === 'none')) {
                return true;
            }
        }
        return false;
    }

    public function isBounce(): bool
    {
        if ($this->isReport) {
            return true;
        }
        $from = strtolower($this->fromEmail);
        return str_starts_with($from, 'mailer-daemon@') || str_starts_with($from, 'postmaster@')
            || (bool)preg_match('/^(undeliver(able|ed)|delivery status notification|mail delivery (failed|subsystem)|returned mail)/i', $this->subject);
    }

    /** @return list<string> */
    public function referencedIds(): array
    {
        $ids = [];
        if ($this->inReplyTo !== '') {
            $ids[] = $this->inReplyTo;
        }
        foreach (array_reverse($this->references) as $r) {
            $ids[] = $r;
        }
        return array_values(array_unique($ids));
    }
}
